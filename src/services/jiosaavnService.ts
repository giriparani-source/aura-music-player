export interface MirrorHealth {
  url: string;
  name: string;
  failureCount: number;
  lastFailureTime: number;
  cooldownUntil: number;
  totalSuccesses: number;
  totalFailures: number;
  isAvailable: boolean;
}

interface InternalMirrorState {
  url: string;
  name: string;
  failureCount: number;
  lastFailureTime: number;
  cooldownUntil: number;
  totalSuccesses: number;
  totalFailures: number;
}

const REQUEST_TIMEOUT_MS = 4000;

class JioSaavnService {
  private cache: Map<string, Song[]> = new Map();

  private mirrors: InternalMirrorState[] = [
    {
      url: 'https://jiosaavn-api-sage.vercel.app',
      name: 'Primary (Sage)',
      failureCount: 0,
      lastFailureTime: 0,
      cooldownUntil: 0,
      totalSuccesses: 0,
      totalFailures: 0
    },
    {
      url: 'https://jiosaavn-api-eight.vercel.app',
      name: 'Secondary (Eight)',
      failureCount: 0,
      lastFailureTime: 0,
      cooldownUntil: 0,
      totalSuccesses: 0,
      totalFailures: 0
    }
  ];

  /**
   * Get health metrics for all configured JioSaavn mirrors.
   */
  public getMirrorHealth(): MirrorHealth[] {
    const now = Date.now();
    return this.mirrors.map((m) => ({
      url: m.url,
      name: m.name,
      failureCount: m.failureCount,
      lastFailureTime: m.lastFailureTime,
      cooldownUntil: m.cooldownUntil,
      totalSuccesses: m.totalSuccesses,
      totalFailures: m.totalFailures,
      isAvailable: now >= m.cooldownUntil
    }));
  }

  /**
   * Fetch from a single mirror with AbortController timeout.
   */
  private async fetchFromMirror(mirror: InternalMirrorState, query: string): Promise<any[] | null> {
    const endpoint = `${mirror.url}/api/search/songs?query=${encodeURIComponent(query)}`;
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

    try {
      const res = await fetch(endpoint, {
        headers: { 'User-Agent': 'Mozilla/5.0' },
        signal: controller.signal
      });

      if (!res.ok) {
        throw new Error(`HTTP ${res.status}`);
      }

      const data = await res.json();
      const results = data?.data?.results || data?.results;

      if (Array.isArray(results)) {
        // Success: reset failure counter and cooldown
        mirror.failureCount = 0;
        mirror.cooldownUntil = 0;
        mirror.totalSuccesses++;
        return results;
      }
      return null;
    } catch (err: any) {
      // Record failure and apply cooldown
      mirror.failureCount++;
      mirror.totalFailures++;
      mirror.lastFailureTime = Date.now();

      // Exponential cooldown: 5s on 1st fail, 30s on 2nd, 60s, up to 5 mins max
      const cooldownMs =
        mirror.failureCount === 1
          ? 5000
          : Math.min(300000, 30000 * Math.pow(2, mirror.failureCount - 2));

      mirror.cooldownUntil = Date.now() + cooldownMs;

      const reason = err.name === 'AbortError' ? `Timeout (${REQUEST_TIMEOUT_MS}ms)` : err.message || 'Request error';
      console.warn(
        `[JioSaavn] Mirror '${mirror.name}' failed: ${reason}. Failure count: ${mirror.failureCount}, cooldown for ${Math.round(cooldownMs / 1000)}s`
      );
      return null;
    } finally {
      clearTimeout(timer);
    }
  }

  public async searchJioSaavn(query: string): Promise<Song[]> {
    const q = query.trim();
    if (!q) return [];

    const cacheKey = q.toLowerCase();
    if (this.cache.has(cacheKey)) {
      return this.cache.get(cacheKey)!;
    }

    try {
      const now = Date.now();

      // Sort mirrors: active ones first (not in cooldown), then by earliest cooldown expiry
      const sortedMirrors = [...this.mirrors].sort((a, b) => {
        const aActive = now >= a.cooldownUntil;
        const bActive = now >= b.cooldownUntil;
        if (aActive && !bActive) return -1;
        if (!aActive && bActive) return 1;
        return a.cooldownUntil - b.cooldownUntil;
      });

      let rawResults: any[] = [];

      for (const mirror of sortedMirrors) {
        const results = await this.fetchFromMirror(mirror, q);
        if (results && results.length > 0) {
          rawResults = results;
          break;
        }
      }

      if (rawResults.length > 0) {
        const queryWords = q.toLowerCase().replace(/[^a-z0-9]/g, ' ').split(/\s+/).filter((w) => w.length >= 3);
        const relevantResults = queryWords.length > 0
          ? rawResults.filter((item: any) => {
              const itemTitle = (item.name || item.title || '').toLowerCase();
              const itemArtist = (item.primaryArtists || item.singers || '').toLowerCase();
              return queryWords.some((w) => itemTitle.includes(w) || itemArtist.includes(w));
            })
          : rawResults;

        const formatted: Song[] = relevantResults.map((item: any) => {
          // Extract 320kbps URL
          const dlUrls = item.downloadUrl || [];
          const bestUrlObj = dlUrls.find((d: any) => d.quality === '320kbps') || dlUrls[dlUrls.length - 1];
          const streamUrl = bestUrlObj?.url || '';

          // Extract best image
          const images = item.image || [];
          const bestImgObj = images.find((i: any) => i.quality === '500x500') || images[images.length - 1];
          const imgUrl = bestImgObj?.url || 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=300';

          const title = item.name || item.title || 'JioSaavn Track';
          const artist = item.primaryArtists || item.singers || item.music || 'Master Artist';
          const album = item.album?.name || 'JioSaavn Studio Master';
          const duration = Number(item.duration) || 210;

          return {
            id: `saavn_${item.id}`,
            sourceId: item.id,
            title,
            artist,
            album,
            duration,
            format: '320k AAC',
            bitrate: 320,
            fileSize: duration * 40000,
            dateAdded: Date.now(),
            playCount: 0,
            isFavorite: false,
            artwork: imgUrl,
            coverArt: imgUrl,
            filePath: streamUrl,
            path: streamUrl,
            fileName: `${title}_320k.m4a`,
            isOnline: true,
            isSaavn: true
          };
        });

        this.cache.set(cacheKey, formatted);
        return formatted;
      }
    } catch (err) {
      console.warn('[JioSaavn] Search exception:', err);
    }

    // Fallback to matching preset hits
    const lower = q.toLowerCase();
    const matchingPresets = PRESET_SAAVN_320K_HITS.filter(
      (s) =>
        s.title.toLowerCase().includes(lower) ||
        s.artist.toLowerCase().includes(lower) ||
        s.album.toLowerCase().includes(lower)
    );

    return matchingPresets;
  }

  public getCuratedHits(): Song[] {
    return PRESET_SAAVN_320K_HITS;
  }
}

export const jiosaavnService = new JioSaavnService();
export const searchJioSaavn = (query: string): Promise<Song[]> => jiosaavnService.searchJioSaavn(query);
export const getMirrorHealth = (): MirrorHealth[] => jiosaavnService.getMirrorHealth();
